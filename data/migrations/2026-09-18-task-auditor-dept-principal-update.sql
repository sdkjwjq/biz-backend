SET t.`auditor_id` = x.`auditor_user_id`,
    t.`dept_id` = x.`dept_resolved_id`,
    t.`principal_id` = x.`principal_user_id`,
    t.`update_time` = NOW()
WHERE t.`is_delete` = 0
  AND x.`auditor_user_id` IS NOT NULL AND x.`principal_user_id` IS NOT NULL AND x.`dept_resolved_id` IS NOT NULL
  AND (COALESCE(t.`auditor_id`, -1) <> x.`auditor_user_id`
    OR t.`dept_id` <> x.`dept_resolved_id`
    OR COALESCE(t.`principal_id`, -1) <> x.`principal_user_id`);

