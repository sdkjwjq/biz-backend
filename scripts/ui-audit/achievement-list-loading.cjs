// Real overview fixture. Gate requests to verify loading without timing-dependent sleeps.
const {chromium,request}=require('../../target/ui-audit-tools/node_modules/playwright');
const {expect}=require('../../target/ui-audit-tools/node_modules/playwright/test');
const fs=require('node:fs/promises'),path=require('node:path'),assert=require('node:assert/strict');
(async()=>{
 const stateFile=process.env.UI_AUDIT_STATE_FILE;assert.ok(stateFile,'Use a dedicated disposable UI run');
 const state=JSON.parse(await fs.readFile(stateFile));assert.match(state.schema,/^biz_review_test_[0-9a-f]{32}$/);
 assert.equal(new URL(state.frontend).hostname,'127.0.0.1');
 const out=path.join(path.dirname(stateFile),'achievement-list-loading');await fs.mkdir(out,{recursive:true});
 const api=await request.newContext({baseURL:state.frontend});
 const response=await api.post('/api/system/login',{data:{user_id:110228,password:'review-fixture-password'}});
 const token=(await response.json()).token;assert.ok(token);
 const browser=await chromium.launch({channel:process.env.UI_AUDIT_BROWSER_CHANNEL||'chrome',headless:true});
 const context=await browser.newContext({viewport:{width:1536,height:864}});
 await context.addInitScript(t=>localStorage.setItem('token',t),token);
 const page=await context.newPage();page.setDefaultTimeout(20000);const checks=[],errors=[];page.on('pageerror',e=>errors.push(e.message));
 let releaseList,releaseTodo,listReleased=false,todoReleased=false,failNext=false,filterRequests=0;
 page.on('request',request=>{if(new URL(request.url()).pathname==='/api/list-filters/achievements')filterRequests++});
 const listGate=new Promise(resolve=>{releaseList=()=>{listReleased=true;resolve()}});
 const todoGate=new Promise(resolve=>{releaseTodo=()=>{todoReleased=true;resolve()}});
 const listUrl=url=>url.pathname==='/api/achievement/';
 await page.route(listUrl,async route=>{if(failNext){failNext=false;return route.fulfill({status:500,contentType:'application/json',body:JSON.stringify({code:500,message:'模拟成果列表失败'})})}if(!listReleased)await listGate;await route.continue().catch(()=>{})});
 await page.route(url=>url.pathname==='/api/achievement/audit/todo',async route=>{if(!todoReleased)await todoGate;await route.continue().catch(()=>{})});
 try {
  await page.goto(state.frontend+'/home/works/achievement');
  await expect(page.locator('.project-actions')).toContainText('正在加载成果');
  await expect(page.getByText('No Data',{exact:true})).toHaveCount(0);
  await expect(page.getByText('共 0 条',{exact:true})).toHaveCount(0);
  await page.screenshot({path:path.join(out,'first-loading.png'),fullPage:true});checks.push('first-load-no-false-empty-or-zero');
  releaseList();
  await expect(page.locator('.el-table__row').first()).toBeVisible();
  await expect(page.locator('.table-wrapper > .el-loading-mask')).toBeHidden();
  await expect(page.locator('.project-actions')).toContainText('共 3 条');
  assert.equal(filterRequests,1);checks.push('initial-list-does-not-repeat-filter-request');
  assert.equal(todoReleased,false);checks.push('slow-audit-shortcut-does-not-block-real-list');
  releaseTodo();await page.locator('.el-table__expand-icon').first().click();
  const rows=page.locator('.el-table__row');const count=await rows.count();assert.ok(count>2);
  await expect(page.locator('.table-card')).toContainText('合成已归档成果');
  await expect(page.locator('.table-card')).toContainText('合成驳回原因');
  await page.screenshot({path:path.join(out,'loaded.png'),fullPage:true});checks.push('tree-and-rejection-details-preserved');
  await rows.filter({hasText:'合成已归档成果'}).getByRole('button',{name:'查看',exact:true}).click();
  failNext=true;await page.getByRole('button',{name:'返回列表并定位',exact:true}).click();
  await expect(page.locator('.table-card > .el-alert')).toContainText('更新失败，当前保留上次成果');
  await expect(rows).toHaveCount(count);await page.screenshot({path:path.join(out,'failed-refresh.png'),fullPage:true});checks.push('failed-refresh-preserves-existing-tree');
  await page.getByRole('button',{name:'重新加载成果',exact:true}).click();
  await expect(page.locator('.table-card > .el-alert')).toHaveCount(0);
  await expect(page.locator('.table-wrapper > .el-loading-mask')).toBeHidden();
  await expect(page.locator('.table-card')).toContainText('合成已归档成果');checks.push('retry-restores-list-with-existing-filters');
  const bar=page.locator('[aria-label="成果筛选"]');
  await bar.getByRole('textbox',{name:'成果成果名称',exact:true}).fill('确实不存在的成果名称');
  await bar.getByRole('button',{name:'查询',exact:true}).click();
  await expect(page.getByText('暂无匹配成果',{exact:true})).toBeVisible();
  await expect(page.locator('.project-actions')).toContainText('共 0 条');checks.push('successful-empty-result-is-distinct-from-loading-and-failure');
  await page.route('**/api/list-filters/achievements?**',route=>route.fulfill({status:500,contentType:'application/json',body:JSON.stringify({code:500,message:'模拟筛选加载失败'})}));
  await page.reload();
  await expect(page.locator('[aria-label="成果筛选"] .el-alert')).toContainText('加载失败');
  await expect(page.getByText('成果加载失败，请重试',{exact:true})).toBeVisible();
  await expect(page.getByText('暂无匹配成果',{exact:true})).toHaveCount(0);
  await expect(page.locator('.project-actions')).toContainText('成果加载失败');checks.push('filter-failure-is-not-presented-as-empty-data');
  assert.deepEqual(errors,[]);await fs.writeFile(path.join(out,'result.json'),JSON.stringify({checks,errors},null,2));console.log(JSON.stringify({checks:checks.length,output:out}));
 }finally{releaseList();releaseTodo();await context.close();await browser.close();await api.dispose()}
})().catch(error=>{console.error(error);process.exitCode=1});
