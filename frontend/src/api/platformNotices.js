import { get, post, upload } from '@/utils/request'
export const noticeStatus = () => get('/platform-notices/status')
export const openPlatformNotice = (id, requestId) => post(`/platform-notices/${id}/open`, { requestId })
export const confirmPlatformNotice = notice => post(`/platform-notices/${notice.id}/confirm`, { contentVersion: notice.contentVersion, viewKey: notice.viewKey })
export const downloadPlatformAttachment = (id, file) => get(`/platform-notices/${id}/attachments/${file}`, {}, { responseType: 'blob' })
export const listPlatformNotices = params => get('/admin/platform-notices', params)
export const platformNoticeOptions = params => get('/admin/platform-notices/options', params)
export const previewPlatformRecipients = data => post('/admin/platform-notices/preview', data)
export const savePlatformNotice = data => post('/admin/platform-notices', data)
export const getPlatformNotice = id => get(`/admin/platform-notices/${id}`)
export const publishPlatformNotice = notice => post(`/admin/platform-notices/${notice.id}/publish`, { version: notice.version })
export const withdrawPlatformNotice = (notice, reason) => post(`/admin/platform-notices/${notice.id}/withdraw`, { version: notice.version, reason })
export const uploadPlatformAttachment = file => upload('/admin/platform-notices/attachments', file)
export const platformNoticeReceipts = (id, params) => get(`/admin/platform-notices/${id}/receipts`, params)
export const platformNoticeEvents = (id, user) => get(`/admin/platform-notices/${id}/events/${user}`)
export const exportPlatformNoticeReceipts = id => get(`/admin/platform-notices/${id}/export`, {}, { responseType: 'blob' })
